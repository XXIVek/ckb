-- Аддитивная миграция V21 для УЖЕ СОЗДАННЫХ баз ckb_1c_configurations.
-- Узел V20.1: снять внешний ключ external_report.configuration_id -> configurations(id).
-- Дата: 14.10.2026.
-- Повторное применение безопасно: DROP CONSTRAINT IF EXISTS. Данные и индекс не теряются.
-- Источник истины — src/generate_ddl.py (шаг 1) и create_1c_configurations_db.sql (шаг 2):
-- оба больше FK не объявляют, поэтому после этой миграции живая БД и чистая установка совпадают
-- (сверка python _cmp_ddl.py, ожидание: расхождений нет, код возврата 0).
-- ============================================================
-- Зачем сняли FK (решение оператора 14.10.2026, тот же день, что и узел V20; норматив —
-- docs/CONFIGURATIONS_ENRICHMENT_PLAN.md, раздел 12, правила D1..D8):
--   * конфигурация для внешнего объекта — СПРАВОЧНАЯ СИСТЕМА: она нужна только при проверке
--     данных отчёта. Ни загрузка каталога, ни генерация обогащения, ни карточка объекта, ни
--     разбор макета-СКД в configurations для своей работы не обращаются;
--   * FK при этом мешал: удалить или пересоздать строку заголовка конфигурации, пока на неё
--     есть привязки, было нельзя, то есть вести справочник было нельзя вовсе;
--   * ошибка приходила в момент записи (сырой текст psycopg2 про external_report_configuration_fkey),
--     а не тогда, когда оператор анализирует отчёт и ему это действительно важно;
--   * вместо внешнего ключа работают два механизма, уже применяемые в проекте к
--     config_cross_references.local_doc_id (ссылка в другую базу, FK невозможен): запись
--     проверяет инструмент set_object_configuration_tool (несуществующая конфигурация
--     отклоняется), а потерявшая заголовок ссылка обнаруживается ПРИ ЧТЕНИИ — карточка объекта
--     и сводка различают not_declared / bound / dangling и прямо требуют перепривязки.
--   * индекс idx_external_report_configuration_id СОХРАНЯЕТСЯ: перепривязка ищется обратным
--     запросом «какие объекты привязаны к конфигурации N» / «где битые ссылки».
--   * снимок имени и версии конфигурации рядом с id НЕ заводится: карточка всегда разрешает
--     ссылку живым JOIN, поэтому переиспользование id новым заголовком видно по другому имени
--     и версии, а не спрятащено в устаревшей копии.
-- ============================================================

ALTER TABLE external_report
    DROP CONSTRAINT IF EXISTS external_report_configuration_fkey;

