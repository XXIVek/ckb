def main() -> int:
    write = "--write" in sys.argv[1:]
    with get_cursor() as cur:
        cur.execute("SELECT id, answer FROM knowledge_snippets WHERE question = %s", (ADDRESS,))
        row = cur.fetchone()
        if not row:
            print(f"⚠️ ОТКАЗ: карточки нет — {ADDRESS}")
            return 1
        snippet_id, answer = row["id"], row["answer"] or ""
        if MARKER in answer:
            print(f"без изменений: {ADDRESS} (id {snippet_id}) — запись шага П8 уже внесена")
            return 0
        pos = answer.find(ANCHOR)
        if pos < 0:
            print(f"⚠️ ОТКАЗ {ADDRESS}: якорь прежней строки не найден — {ANCHOR!r}")
            return 1
        print(f"заменяемый хвост ({len(answer) - pos} симв.):")
        print(answer[pos:pos + 300])
        new_answer = answer[:pos] + NEW_TAIL
        print(f"\nкарточка id {snippet_id}: было {len(answer)} симв., станет {len(new_answer)}")
        if not write:
            print("Режим отчёта: строка не изменена (ключ --write включает запись)")
            return 0
        cur.execute("UPDATE knowledge_snippets SET answer = %s WHERE id = %s",
                    (new_answer, snippet_id))
        cur.connection.commit()
        print(f"записано: {ADDRESS}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
