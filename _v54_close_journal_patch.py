def main():
    dry = "--write" not in sys.argv
    with get_cursor() as cur:
        ok = 0
        total = 0
        for start, end, new, label in (
            (J_OPEN_START, J_OPEN_END, J_OPEN_NEW, "абзац закрытия узла вместо «открыт»"),
            (J_SHOT_START, None, J_SHOT_NEW, "перечень шагов в строке снимка П0–П5 → П0–П9"),
            (J_TAIL_START, J_TAIL_END, J_TAIL_NEW, "итоги шагов П6–П9 вместо «не закрываются»"),
        ):
            total += 1
            if replace_span(cur, ADDRESS, start, end, new, label, dry):
                ok += 1
        print(f"\n{'ПРОГОН БЕЗ ЗАПИСИ' if dry else 'ЗАПИСЬ'}: правок {ok} из {total} — {ADDRESS}")
        if dry:
            print("для записи: python _v54_close_journal_patch.py --write")
        return 0 if ok == total else 1


if __name__ == "__main__":
    sys.exit(main())

