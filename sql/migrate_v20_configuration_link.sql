-- Аддитивная миграция V20 для УЖЕ СОЗДАННЫХ баз ckb_1c_configurations.
-- Узел V20: привязка внешнего объекта к конфигурации, заявленная оператором.
-- Дата: 14.10.2026.
-- Повторное применение безопасно: ADD COLUMN IF NOT EXISTS, CREATE INDEX IF NOT EXISTS и
-- DO-блок с проверкой pg_constraint. Данные не теряются.
-- Источник истины по колонке и индексу — src/generate_ddl.py (шаг 1 установки,
-- src/ddl_external_report.sql). FK этим узлом НЕ добавляется: он был добавлен изначально
-- и снят узлом V20.1 того же дня (см. migrate_v21_drop_configuration_fk.sql) — здесь блок FK
-- убран, чтобы любая цепочка применения (чистая установка, V20, V20+V21) приходила к одной
-- и той же схеме: колонка + индекс, внешнего ключа нет.
-- ============================================================
-- Смысл (решение оператора 14.10.2026, docs/CONFIGURATIONS_ENRICHMENT_PLAN.md, узел V20):
--   * external_report.configuration_id — id строки заголовка конфигурации (configurations.id),
--     к которой оператор привязал внешний отчёт. Имя и тип — те же, что у существующих ссылок
--     config_extensions.configuration_id, external_processing.configuration_id,
--     bsl_modules.configuration_id.
--   * NULL = привязка НЕ заявлена. Это НЕ «отчёт универсальный»: отдельного состояния
--     «универсальный» в модели нет, автоматической классификации тоже нет (отложено).
--   * FK НЕ объявляется (пересмотрено узлом V20.1, 14.10.2026, тот же день). Изначально узел
--     V20 добавлял external_report_configuration_fkey без ON DELETE — как у ссылок
--     config_extensions / external_processing / bsl_modules. От внешнего ключа отказались:
--     конфигурация — справочная система, которая нужна только при проверке данных отчёта, а FK
--     блокировал бы удаление заголовка и давал ошибку в момент записи через psql, а не при
--     анализе объекта. Целостность проверяет set_object_configuration_tool (битый id
--     отклоняется), потерянная ссылка обнаруживается при чтении: карточка и сводка различают
--     «не заявлена» / «привязано» / «битая, требуется перепривязка». Тот же контракт, что у
--     config_cross_references.local_doc_id.
--   * uuid конфигурации в этой связи не используется: ссылка идёт на строку заголовка, а не
--     на идентификатор метаданных 1С. Если строка заголовка удалена — привязка становится
--     битой, карточка объекта прямо требует перепривязки; при NULL карточка пишет
--     «привязка не заявлена», а не «универсальный».
--   * force=True: загрузчик переносит прежнее значение на новую строку
--     (src/external_report_loader.py), потому что привязка заявлена оператором и из
--     выгрузки 1С не восстанавливается.
-- ============================================================

ALTER TABLE external_report ADD COLUMN IF NOT EXISTS configuration_id INTEGER;

CREATE INDEX IF NOT EXISTS idx_external_report_configuration_id
    ON external_report(configuration_id);

