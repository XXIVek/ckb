#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""_make_position_frame.py — DDL пакета позиций выводится из спецификации (узел V59).

Зачем. Правка схемы по правилу слоя обязана идти парой «миграция + зеркало в DDL-источнике»
(`sql/migrate_vNN_*.sql` и `sql/create_1c_configurations_db.sql`), и до этого узла оба
файла писались от руки для каждой позиции — по 60–120 строк на позицию, одинаковых кроме
имён колонок. Здесь тот же текст порождается строкой контракта
(`src/configuration_position_spec.py`): второй копии колонок в репозитории не появляется,
а проверка `tools/check_position_frame.py` сверяет живую схему с тем же источником.

Что делает прогон:
  1. пишет `sql/migrate_v59_position_frame.sql` (аддитивная миграция пакета);
  2. вставляет тот же блок в `sql/create_1c_configurations_db.sql` между маркерами —
     повторный прогон заменяет блок между маркерами, а не добавляет второй;
  3. печатает число позиций, таблиц, витрин и строк — ответ называется числом.

Сверку пары живая БД ↔ файлы обеспечивает `python probes/misc/_cmp_ddl.py` (он строит
временную базу теми же шагами), поэтому отдельной «своей» сверки генератор не требует.

Запуск из корня репозитория:  python tools/_make_position_frame.py
"""
from __future__ import annotations

import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from configuration_position_spec import (  # noqa: E402
    FRAME_NODE, MEASURE_DATE, ordered_specs, position_ddl, expected_total,
)

MIGRATION = ROOT / "sql" / "migrate_v59_position_frame.sql"
MIRROR = ROOT / "sql" / "create_1c_configurations_db.sql"
MARK_BEGIN = "-- >>> begin пакет позиций V59 (generated by tools/_make_position_frame.py)"
MARK_END = "-- <<< end пакет позиций V59"

HEADER = f"""-- migrate_v59_position_frame.sql
-- ============================================================================
-- Узел {FRAME_NODE}, шаг П2: пакет позиций списка (кластер «плоская регистрация») —
-- DDL десяти таблиц выведен строкой контракта `src/configuration_position_spec.py`,
-- а не написан от руки. Правка круга позиции = правка строки спецификации и повторный
-- прогон этого генератора; второго описания колонок в репозитории нет.
--
-- Круг и ожидаемые счётчики доказаны замером `probes/v59/_v59_p0_frame_probe.py`
-- ({MEASURE_DATE}) по четырём выгрузкам; сверку круга с живой схемой и с выгрузками
-- держит `python tools/check_position_frame.py`.
--
-- Миграция аддитивна по строкам; итоговое состояние совпадает с чистой установкой
-- (шаг 3 = {MIRROR.name}). Сверка пары — `python probes/misc/_cmp_ddl.py`.
--
-- Чем позиции пакета отличаются от видов V48–V58 — названо, а не сглажено:
--   * файл регистрации — `<Контейнер>/<Имя>.xml`, а не `<Имя>.mdo`; содержимое `Ext/`
--     тоже бывает XML (`Picture.xml`, `Template.xml`, `WSDefinition.xml`) и регистрацией
--     не является: без этого различения круг CommonPictures завышается вдвое
--     (2 029 объектов против 4 058 файлов в BP3);
--   * у шести позиций есть содержимое (`Ext/`), и в этом узле оно считается числом и
--     состоянием, но не разбирается: круг содержимого — отдельная работа;
--   * у двух позиций контейнера нет в трёх из четырёх выгрузок (Styles,
--     ExternalDataSources) — это ответ о выгрузке, и он называется состоянием стадии.
-- ============================================================================
"""


def block() -> str:
    parts = []
    for spec in ordered_specs():
        parts.append(
            f"\n-- позиция {spec['position']} — {spec['title']} "
            f"(контейнер `{spec['container']}`, вид `{spec['kind_tag']}`, "
            f"ожидаемых объектов по четырём выгрузкам: {expected_total(spec)})\n"
            + position_ddl(spec)
        )
    return MARK_BEGIN + "\n" + "\n\n".join(parts) + "\n" + MARK_END + "\n"


def write_migration() -> None:
    MIGRATION.write_text(HEADER + "\n" + block(), encoding="utf-8")


def write_mirror() -> str:
    text = MIRROR.read_text(encoding="utf-8")
    new_block = block()
    if MARK_BEGIN in text and MARK_END in text:
        start = text.index(MARK_BEGIN)
        end = text.index(MARK_END) + len(MARK_END) + 1
        updated = text[:start] + new_block + text[end:]
        action = "заменён"
    else:
        updated = text.rstrip() + "\n\n" + new_block
        action = "добавлен"
    MIRROR.write_text(updated, encoding="utf-8")
    return action


def main() -> int:
    specs = ordered_specs()
    write_migration()
    action = write_mirror()
    print(f"Спецификаций позиций: {len(specs)}")
    for spec in specs:
        print(f"  {spec['position']:<5} {spec['table']:<22} {spec['view']:<28} "
              f"объектов по кругу: {expected_total(spec)}")
    print(f"Миграция: {MIGRATION}")
    print(f"Зеркало:  {MIRROR} — блок {action}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
