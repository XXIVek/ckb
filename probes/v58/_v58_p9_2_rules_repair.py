def read_card(address):
    from database import get_cursor

    with get_cursor() as cur:
        cur.execute("SELECT id, answer FROM knowledge_snippets WHERE question = %s", (address,))
        return cur.fetchone()


def apply_cards(write):
    """Правки карточек: old обязан встретиться ровно один раз, сначала guard нового текста."""
    from mcp_tools_api import update_snippet

    problems = []
    by_card = {}
    for address, old, new in CARD_EDITS:
        by_card.setdefault(address, []).append((old, new))

    for address, edits in by_card.items():
        row = read_card(address)
        if not row:
            problems.append(f"карточка `{address}` не найдена")
            continue
        answer = row["answer"]
        original = answer
        marks = []
        for old, new in edits:
            if new in answer:
                marks.append("УЖЕ")
                continue
            hits = answer.count(old)
            if hits != 1:
                marks.append(f"НЕ СОШЛОСЬ ({hits} вхождений old)")
                continue
            answer = answer.replace(old, new, 1)
            marks.append("ПРИМЕНЕНО")
        applied = sum(1 for mark in marks if mark == "ПРИМЕНЕНО")
        print(f"  {address}: {len(original)} -> {len(answer)} симв. — " + "; ".join(marks))
        if write and applied:
            res = update_snippet(row["id"], new_answer=answer, reason=REASON)
            if isinstance(res, dict) and not res.get("ok", True):
                problems.append(f"update_snippet `{address}`: {res}")
    return problems


def append_journal(write):
    row = read_card(JOURNAL)
    if not row:
        return [f"карточка `{JOURNAL}` не найдена - снимок узла не дополняется"]
    answer = row["answer"]
    if JOURNAL_MARK in answer:
        print(f"  без изменений (уже применено): {JOURNAL} ({len(answer)} симв.)")
        return []
    target = answer + JOURNAL_APPEND
    print(f"  {'дополняется' if write else 'будет дополнена'}: {JOURNAL} "
          f"({len(answer)} -> {len(target)} симв.)")
    if write:
        from mcp_tools_api import update_snippet

        res = update_snippet(row["id"], new_answer=target, reason=REASON)
        if isinstance(res, dict) and not res.get("ok", True):
            return [f"update_snippet `{JOURNAL}`: {res}"]
    return []


def main():
    write = "--write" in sys.argv[1:]
    print("=== узел V58 П9-2: приведение карточек слоя к живому состоянию ===",
          "запись" if write else "только разбор")
    problems = apply_cards(write)
    problems += append_journal(write)
    if problems:
        print("--- расхождения ---")
        for line in problems:
            print("  " + line)
        return 1
    print("--- расхождений нет ---")
    return 0


