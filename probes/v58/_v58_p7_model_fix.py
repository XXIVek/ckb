def detect_eol(text: str) -> str:
    return "\r\n" if "\r\n" in text else "\n"


def edit_files(write: bool):
    """Правки текстов документов; каждая требует ровно одного вхождения старого текста."""
    problems = []
    for rel, old, new, expect in EDITS:
        path = ROOT / rel
        if not path.exists():
            problems.append(f"{rel}: файла нет")
            continue
        raw = path.read_text(encoding="utf-8", newline="")
        eol = detect_eol(raw)
        old_eol = old.replace("\n", eol)
        new_eol = new.replace("\n", eol)
        if raw.count(new_eol) >= expect:
            print(f"  без изменений (уже применено): {rel}")
            continue
        count = raw.count(old_eol)
        if count == 0:
            problems.append(f"{rel}: подстрока не найдена ({old.splitlines()[0][:60]})")
            continue
        if count != expect:
            problems.append(f"{rel}: подстрока встречается {count} раз, ожидалось {expect}")
            continue
        if write:
            path.write_text(raw.replace(old_eol, new_eol), encoding="utf-8", newline="")
            print(f"  применено ({count}): {rel}")
        else:
            print(f"  будет заменено ({count}): {rel} ({old.splitlines()[0][:60]})")
    return problems


def patch_journal(write: bool):
    """Раздел П7 дописывается в снимок узла; прежнее содержимое уходит в аудит-лог.

    Раздел перечитываемся целиком: круг правки расширился по итогам прогона по живому тексту,
    поэтому первая редакция раздела не является окончательной. Содержимое карточки до каждой
    записи сохраняется `snippet_audit_log` (`action=fix`).
    """
    from database import get_cursor
    from mcp_tools_api import update_snippet

    with get_cursor() as cur:
        cur.execute("SELECT id, answer FROM knowledge_snippets WHERE question = %s", (JOURNAL,))
        row = cur.fetchone()
    if not row:
        return [f"карточка `{JOURNAL}` не найдена - снимок узла не дополняется"]
    answer = row["answer"]
    if JOURNAL_MARK in answer:
        base = answer[:answer.index(JOURNAL_MARK)].rstrip()
        target = base + JOURNAL_APPEND
        if target == answer:
            print(f"  без изменений (уже применено): {JOURNAL} ({len(answer)} симв.)")
            return []
        print(f"  {'дополняется заново' if write else 'будет дополнена заново'}: {JOURNAL} "
              f"({len(answer)} -> {len(target)} симв.)")
    else:
        target = answer + JOURNAL_APPEND
        print(f"  {'дополняется' if write else 'будет дополнена'}: {JOURNAL} "
              f"({len(answer)} -> {len(target)} симв.)")
    if write:
        res = update_snippet(row["id"], new_answer=target,
                             reason="узел V58 шаг П7: модель и границы перестали утверждать, что "
                                    "определяемых типов нет в выгрузках")
        if isinstance(res, dict) and not res.get("ok", True):
            return [f"update_snippet: {res}"]
    return []


