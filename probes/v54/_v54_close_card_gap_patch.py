# -*- coding: utf-8 -*-
"""V54, закрытие узла: исправление лаксуны перечня снимков журнала в карточках слоя (правка после закрытия).

Повод. Карточка `rules:core-rules:functional:goal-and-stages` в разделе `===SOURCE===`
перечисляет «историю стадий — разрешимыми адресами снимка слоя» до `…journal:node:v52`, хотя
карточки `…node:v53` и `…node:v54` в базе есть, и индекс ветки `journal` их отдаёт. Зонд
`_v54_close_card_gap_probe.py` поднял, что обрыв не единственный:

* `rules:core-rules:functional:goal-and-stages` — перечня нет для v53 и v54;
* `rules:core-rules:functional:load-catalog` — перечень доведён до v53, строки v54 нет
  (шаг П5 узла V54 правил матрицу стадий, FORBID и числа ветки `journal`, но не этот перечень);
* `rules:core-rules:load-exchange-plans-tool` — ссылается только на снимок своего узла v51,
  и это не расхождение: карточка инструмента называет тот узел, который менял его контракт.

Числа ветки `journal` при этом сходятся с базой: карточка слоя говорит «92 карточки» (замер
`_v54_p5_journal_count.py`, вместе с карточкой-индексом), индекс ветки — «91 карточка снимка»
(без индекса). Замер 03.11.2026 подтверждает: 31 снимок узла + 29 снимков позиций + 31 снимок
прежних текстов + индекс = 92. То есть дефект — только в перечне, заведённом словами.

Причина дефекта названа в самой правке: перечень, который ведётся руками, отстаёт от базы ровно
на тот шаг, который о нём не вспомнил (тот же вывод, из-за которого карточка слоя отказалась
хранить числа состава в тексте). Поэтому правка делает две вещи: доводит перечень до фактического
состава и называет индекс ветки полным составом, а обязанность пополнения — шагом узла, который
создаёт его карточку журнала.

Границы, а не весь абзац: карточка несёт свои переносы (правило `_v48_p7_rule_patch.replace_span`).
Прогон без `--write` ничего не меняет; повторный прогон с `--write` идемпотентен.
"""

import sys

sys.path.insert(0, "src")
sys.path.insert(0, "probes/v48")  # ROOT-RESTRUCTURE: общий модуль _v48_p7_rule_patch лежит в круге доказательств узла v48

from database import get_cursor  # noqa: E402
from _v48_p7_rule_patch import replace_span  # noqa: E402

GOAL = "rules:core-rules:functional:goal-and-stages"
LOAD = "rules:core-rules:functional:load-catalog"

# --- карточка goal-and-stages -------------------------------------------------------------

G_FRAME_START = "История стадий — разрешимыми адресами снимка слоя:"
G_FRAME_NEW = (
    "История стадий — разрешимыми адресами снимка слоя. Полный состав ветки называет индекс\n"
    "`rules:core-rules:journal:index`, а перечень ниже пополняется тем же шагом узла, который\n"
    "создаёт его карточку журнала: список, заведённый словами, отстаёт от базы на тот шаг, о\n"
    "нём не вспомнили (то же правило, из-за которого карточка слоя не хранит числа состава):"
)

G_LIST_START = (
    "`rules:core-rules:journal:node:v52` (свойства критериев отбора, стадия S4g, "
    "точка входа группы без групп `kinds`, реестр 9→10),"
)
G_LIST_END = "\n\n`rules:core-rules:journal:node:rule-file-removal`"
G_LIST_NEW = (
    "`rules:core-rules:journal:node:v52` (свойства критериев отбора, стадия S4g, "
    "точка входа группы без групп `kinds`, реестр 9→10),\n"
    "`rules:core-rules:journal:node:v53` (свойства подписок на события, стадия S4h, "
    "точка входа группы без групп `kinds`, реестр 10→11),\n"
    "`rules:core-rules:journal:node:v54` (свойства регламентных заданий и записей их "
    "расписания, стадия S4i, точка входа группы без групп `kinds`, реестр 11→12),\n"
    "\n`rules:core-rules:journal:node:rule-file-removal`"
)

# --- карточка load-catalog ---------------------------------------------------------------
# Строки перечня здесь заканчиваются точкой и не несут числа реестра — стиль карточки
# инструмента сохраняется; строка v53 является последней строкой карточки, поэтому конец
# фрагмента не указывается (замена только начала, остаток текста не трогается).

L_V53_LINE = (
    "`rules:core-rules:journal:node:v53` (свойства подписок на события, стадия S4h, "
    "точка входа группы без групп `kinds`)."
)
L_NEW = (
    L_V53_LINE
    + "\n`rules:core-rules:journal:node:v54` (свойства регламентных заданий и записей их "
    "расписания, стадия S4i, точка входа группы без групп `kinds`)."
)


def main():
    dry = "--write" not in sys.argv
    print("=== правка перечней снимков журнала в двух карточках слоя core-rules ===")
    print("режим:", "сухо (запись не делается)" if dry else "запись")
    edits = (
        (GOAL, G_FRAME_START, None, G_FRAME_NEW,
         "полный состав ветки = индекс, обязанность пополнения = шаг узла"),
        (GOAL, G_LIST_START, G_LIST_END, G_LIST_NEW,
         "строки v53 и v54 в перечень истории стадий"),
        (LOAD, L_V53_LINE, None, L_NEW, "строка v54 в перечень истории стадий"),
    )
    ok = 0
    # Курсор открывается здесь, а не в блоке `__main__`: `get_cursor` коммитит после выхода из
    # `yield`, а `sys.exit()` внутри `with` бросает SystemExit в генератор — `except Exception`
    # его не перехватывает, `conn.commit()` не выполняется, и соединение уходит в пул
    # незаписанным (проверено 03.11.2026: прогон с `--write` напечатал «правка», а строки
    # остались прежними). Прецедент формы — `_v54_close_journal_patch.py`.
    with get_cursor() as cur:
        for address, start, end, new, label in edits:
            if replace_span(cur, address, start, end, new, label, dry):
                ok += 1
    print()
    print(f"правок внесено: {ok} из {len(edits)}")
    if dry and ok == len(edits):
        print("правки не внесены: нужен запуск с --write")
    if not dry and ok == len(edits):
        print("после записи: python _layer_tree_check.py; "
              "python tools/check_rules_layer.py --layer core-rules")
    return 0 if ok == len(edits) else 1


if __name__ == "__main__":
    sys.exit(main())


