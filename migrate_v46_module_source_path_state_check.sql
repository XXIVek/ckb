-- migrate_v46_module_source_path_state_check.sql
-- ============================================================================
-- Узел V46, поправка C-V46-1 (шаг П4): CHECK пары «путь ↔ состояние» в
--       common_module_sources разрешает путь ЛЮБОМУ состоянию с текстом модуля,
--       а не только 'file'.
-- Норматив: docs/CONFIGURATION_OBJECT_PROPERTIES_PLAN.md (решение D9 — состояния
--           называются, а не замалчиваются; раздел 4 — модель таблицы).
-- Дата: 2026-10-28.
--
-- Основание. Предикат `content_state = 'file'` уже собственного комментария DDL:
--   «путь есть — состояние обязано называть текст».
-- Состояние `file_not_in_index` по D9 — это файл текста, которого нет в индексе
-- состава: файл существует физически, и путь к нему — ровно то знание, ради
-- которого строка дескриптора существует. Оставить ей NULL-путь — значит
-- замолчать состояние (против D9) и сделать строку нечитаемой: чем она отличается
-- от `file`, по выдаче видно не было бы.
-- Граница CHECK при этом сохраняется в том же смысле: пути нет у состояний без
-- текста (`bin_only`, `indexed_no_file`) — «пути нет» и «текста нет» остаются
-- одним и тем же состоянием. Путь `Module.bin` в колонку по-прежнему не кладётся
-- (он выводится из каталога объекта детерминированно), поэтому `bin_only` остаётся
-- без пути.
--
-- Миграция аддитивна по данным: строк в таблице нет (замер П1 — 0), ни одна
-- колонка не снимается, повторный прогон ничего не меняет (DROP IF EXISTS + ADD).
-- Итоговое состояние совпадает с чистой установкой: тот же предикат ставится в
-- шаг 2 create_1c_configurations_db.sql. Сверка — tools/_cmp_ddl.py.
-- ============================================================================

BEGIN;

ALTER TABLE common_module_sources
    DROP CONSTRAINT IF EXISTS common_module_sources_path_state_check;

ALTER TABLE common_module_sources
    ADD CONSTRAINT common_module_sources_path_state_check
    CHECK (file_path IS NULL OR content_state IN ('file', 'file_not_in_index'));

COMMIT;
