# ------------------------------------------------------------------ теги и алиасы
def rule_tags(kind=STATE_TAG):
    """Теги правила дерева: категории корня и своего слоя, признаки дерева, тег состояния.

    Категории двух слоёв нужны затем, что правило ищут и фильтром корня, и фильтром своего
    сервера: фильтр — пересечение тегов, поэтому тег единственной категории сделал бы правило
    невидимым для второго входа. `tree-rule` отделяет лист дерева от карточек-узлов (`tree-node`)
    и от строк прежнего слоя. Тег состояния остаётся затем, что адрес его больше не несёт: без
    него не восстановить, когда карточку читать, — это то, что в прежней схеме делал сегмент
    `always` / `optional`.
    """
    return list(dict.fromkeys(
        list(RL.categories_of(RL.ROOT_MARKER)) + list(RL.categories_of(LAYER))
        + ["rules", "rules-layer", "tree-rule", kind]))


def level_aliases(address):
    """Алиасы каждого уровня адреса: `rules:`, `rules:kb-rules:`, `rules:kb-rules:functional:`.

    Дампер отдаёт поддерево только тем карточкам, которые объявили алиас уровня (`by_alias` в
    `src/rules_report.py`). Прежний перечень строил уровни одного предка — слоя: пока функции
    лежали уровнем 3, этого хватало, а после переноса под `functional:` префиксный запрос
    `rules:kb-rules:functional:` не нашёл ни одной из них (замер 27.10.2026: отдавались две
    карточки, которым алиас уровня добавил другой шаг). Каждый уровень адреса — отдельный вход,
    и строка обязана объявить их все.
    """
    parts = (address or "").split(":")
    return [":".join(parts[:i]) + ":" for i in range(1, len(parts)) if any(parts[:i])]


def rule_aliases(leaf):
    """Алиасы правила: адрес в двух написаниях, алиасы уровней предков, метка слоя.

    Алиасы уровней (`rules:`, `rules:kb-rules:`, `rules:kb-rules:functional:`) — часть контракта
    дампера: `by_alias` в `src/rules_report.py` отдаёт поддерево только тем карточкам, которые
    объявили алиас уровня. Без них `--query "rules:kb-rules:"` вернул бы одну карточку слоя.
    """
    address = f"{LAYER_ADDRESS}{leaf}"
    short = f"{LAYER}:{leaf}"
    return list(dict.fromkeys(
        [address, short] + level_aliases(address) + level_aliases(short) + [LAYER]))


def ensure_aliases(cur, snippet_id, aliases, tags):
    """Добавить алиасы строки; существующий алиас не дублируется (ON CONFLICT DO NOTHING)."""
    for alias in aliases:
        cur.execute(
            "INSERT INTO alias_targets (alias_name, target_type, groups_id, snippets_id, tags, "
            "weight) VALUES (%s,'snippet',NULL,%s,%s,1.0) "
            "ON CONFLICT (alias_name, snippets_id) WHERE snippets_id IS NOT NULL DO NOTHING",
            (alias, snippet_id, tags),
        )


def ensure_layer_ancestor_alias(cur):
    """Карточкам второго уровня — алиас корня `rules:`.

    Алиас уровня носит каждая карточка поддерева; карточки слоёв его не получили при создании, и
    из-за этого `--query rules:` отдавал одну корневую карточку. Класс дефекта «пустой файл
    прочитался бы как „правил нет“».
    """
    for marker in [m for m in RL.markers() if m != RL.ROOT_MARKER]:
        address = f"{RL.ROOT_MARKER}:{marker}:"
        cur.execute("SELECT id, tags FROM knowledge_snippets WHERE question = %s AND source_url = %s",
                    (address, RL.source_url(address)))
        row = cur.fetchone()
        if not row:
            print(f"⚠️ {address} в базе нет — алиас корня добавлять некуда.")
            continue
        ensure_aliases(cur, row["id"], [f"{RL.ROOT_MARKER}:"], list(row["tags"]) or [])


# ------------------------------------------------------------------ запись правила
def write_rule(cur, leaf, answer, aliases_ru, kind=STATE_TAG, dry=False):
    """Одна карточка третьего уровня: UPDATE вместо INSERT, когда строка с адресом уже есть.

    Идемпотентность по адресу, а не по id: повторный прогон не плодит вторую строку того же
    правила и не меняет id — на них ссылается перечень родительской карточки.
    """
    address = f"{LAYER_ADDRESS}{leaf}"
    problems = RL.validate_address(address, RL.ROOT_MARKER)
    if problems:
        raise ValueError(f"адрес {address!r} не проходит проверку: " + "; ".join(problems))
    tags = rule_tags(kind)
    aliases = rule_aliases(leaf) + list(aliases_ru)
    if dry:
        print(f"• {address} — answer {len(answer)} симв., алиасов {len(aliases)}, теги {tags}")
        return None, "dry-run"
    cur.execute("SELECT id FROM knowledge_snippets WHERE question = %s AND source_url = %s",
                (address, RL.source_url(address)))
    row = cur.fetchone()
    if row:
        cur.execute(
            "UPDATE knowledge_snippets SET answer = %s, tags = %s, confidence = 1.0, "
            "is_verified = TRUE, updated_at = NOW() WHERE id = %s",
            (answer, tags, row["id"]),
        )
        snippet_id, action = row["id"], "обновлено"
    else:
        cur.execute(
            "INSERT INTO knowledge_snippets (groups_id, question, answer, source_url, tags, "
            "confidence, is_verified) VALUES (NULL,%s,%s,%s,%s,1.0,TRUE) RETURNING id",
            (address, answer, RL.source_url(address), tags),
        )
        snippet_id, action = cur.fetchone()["id"], "создано"
    ensure_aliases(cur, snippet_id, aliases, tags)
    return snippet_id, action


# ------------------------------------------------------------------ перечень слоя
def children_rows(cur):
    """Строки живых детей слоя (id, вопрос, answer) в порядке дерева.

    Сама карточка слоя под `LIKE`-условие подходит (её адрес заканчивается двоеточием), поэтому её
    имя исключается явно: перечень, где слой перечисляет сам себя, читается как правило уровня 3.

    Помеченные к удалению дети исключаются фильтром карантина (`src/quarantine.py`): перечень слоя —
    читающая поверхность, а читающие поверхности скрытые строки не отдают. Без фильтра пять снятых
    функциональных карточек стояли бы в перечне рядом с живыми (замер 25.10.2026).

    Журнал и проверки из перечня исключены отдельно: `journal` и `checks` — отдельные сущности дерева
    (`RESERVED_SEGMENTS` и `node_kind` в `src/rules_layer.py`), а не правила. Перечислить их среди
    правил слоя — значит выдать снимок и проверку за действующее правило; их читает дамп, который
    показывает их отдельными разделами в конце файла.
    """
    cur.execute(
        "SELECT id, question, answer, tags FROM knowledge_snippets "
        "WHERE question LIKE %s AND question <> %s AND source_url LIKE %s" + sql_not_marked(),
        (LAYER_ADDRESS + "%", LAYER_ADDRESS, RL.SOURCE_SCHEME + "%", MARK_ARRAY),
    )
    rows = [dict(row) for row in cur.fetchall()
            if RL.node_kind(row["question"]) not in (RL.KIND_JOURNAL, RL.KIND_CHECKS)]
    return sorted(rows, key=lambda row: tree_key(row["question"]))


def tree_children(cur):
    """Дети слоя в дереве (`rules:kb-rules:<что-то>`) — таблицей и списком адресов."""
    rows = children_rows(cur)
    table = ["| id | адрес | когда нужен |", "|---:|---|---|"]
    table += [f"| {row['id']} | `{row['question']}` | {when_hint(row['answer'])} |" for row in rows]
    return "\n".join(table), [row["question"] for row in rows], len(rows)


def block_span(text, heading):
    """Интервал блока по его заголовку: (начало строки заголовка, граница конца, позиция заголовка).

    Граница — следующий заголовок или начало раздела: вставка без границы удваивала бы блок при
    каждом повторном прогоне. Интервал один на модуль — замена, снятие и предпросмотр считают
    границу одинаково; два способа нашли бы разные концы одного блока.
    """
    match = re.search(rf"(?:^|(?<=\s)){re.escape(heading)}[ \t]*$", text or "", re.M)
    if not match:
        return None
    line_start = text.rfind("\n", 0, match.start()) + 1
    rest = text[match.end():]
    stop = re.search(r"(?m)^(?:#{1,6} |===)", rest)
    return line_start, match.end() + (stop.start() if stop else len(rest)), match.start()


def replace_block(text, heading, block):
    """Заменить блок по его заголовку либо дописать, если блока ещё нет.

    Заголовок ищется так, чтобы не спутать его с упоминанием в чужом тексте: совпадением считается
    только строка, оканчивающаяся заголовком (сама по себе или приклеенная к концу чужой строки).
    Два состояния проверены на живом тексте 25.10.2026: поиск подстрокой находил упоминание
    `### Работа с правилами: действия` внутри указателя и вставлял блок в середин абзаца, а поиск
    строго с начала строки этот же приклеенный заголовок не находил — блок дописывался вторым, и
    карточка росла на копию при каждом прогоне.
    """
    span = block_span(text, heading)
    if span is None:
        # блока с таким заголовком нет; если в тексте осталась его копия без заголовка — снимаем
        body = block.strip()
        if body in text:
            text = text.replace(body, "").rstrip()
        return (text.rstrip() + "\n\n" + block).strip()
    line_start, end, match_start = span
    prefix = text[:line_start]
    if text[line_start:match_start].strip():
        prefix = text[:match_start].rstrip() + "\n\n"   # заголовок был приклеен — отделяем
    # Разделитель справа обязателен: граница блока — следующий заголовок, и без перевода строки
    # заголовок приклеивался к последней строке блока (замер 26.10.2026: указатель «действия
    # описаны блоком … ниже» слился с самим заголовком блока).
    return (prefix + block.rstrip() + "\n\n" + text[end:]).strip()


def remove_block(text, heading):
    """Снять блок вместе с заголовком (пустая замена тем же интервалом).

    Нужен затем, что пересобираемый блок меняет заголовок: оставить прежний текст в карточке —
    значит держать в ней перечень, который больше никто не генерирует (он отстаёт от состава слоя
    молча).
    """
    if block_span(text, heading) is None:
        return text
    return replace_block(text, heading, "")


def extract_block(text, heading):
    """Текст блока по его заголовку; пустая строка, если блока нет (для предпросмотра)."""
    span = block_span(text, heading)
    return text[span[0]:span[1]].strip() if span else ""


_SECTION_HEAD_RE = re.compile(r"(?m)^===[ \t]*([A-ZА-Я][A-ZА-Я_]*)")


def section_spans(answer):
    """Интервалы разделов карточки: (имя, начало, конец), включая строку-маркер.

    Разделы правляются по месту, а не пересобираются из кусков. `split_card` отдаёт только
    названные разделы, и сборка заново теряла всё, что стоит до первого маркера: замер 25.10.2026 —
    карточка слоя похудела на 700 символов при повторном прогоне именно потому, что её общая часть
    никуда не входила.
    """
    marks = [(m.group(1), m.start()) for m in _SECTION_HEAD_RE.finditer(answer or "")]
    return [(name, start, marks[i + 1][1] if i + 1 < len(marks) else len(answer or ""))
            for i, (name, start) in enumerate(marks)]


def replace_section(answer, name, new_body):
    """Заменить содержимое раздела по имени, не трогая соседей; если раздела нет — дописать."""
    for section, start, end in section_spans(answer):
        if section == name:
            return (answer[:start] + f"==={name}\n" + new_body.strip() + "\n\n"
                    + answer[end:].lstrip("\n"))
    return (answer.rstrip() + f"\n\n==={name}\n" + new_body.strip() + "\n")


def edit_section(answer, name, transform):
    """Применить функцию к содержимому раздела, сохранив маркер и соседей."""
    for section, start, end in section_spans(answer):
        if section != name:
            continue
        head = answer[start:end]
        cut = head.index("\n") + 1 if "\n" in head else len(head)
        return (answer[:start] + head[:cut] + transform(head[cut:]).strip() + "\n\n"
                + answer[end:].lstrip("\n"))
    return answer


TOOL_RE = re.compile(r"\b([a-z][a-z0-9_]*_tool)\b")


def section_body(answer, name):
    """Содержимое раздела вместе со строкой-маркером; пустая строка, если раздела нет."""
    for section, start, end in section_spans(answer):
        if section == name:
            return answer[start:end]
    return ""


def section_text(answer, name):
    """Тело раздела карточки без строки-маркера.

    Маркер снимается полностью, включая закрывающие `===`: разбор оставил их началом тела (описано
    в `aliases_of`), и в строку указателя попал бы текст вида «— === WHEN».
    """
    body = section_body(answer or "", name)
    if not body:
        return ""
    cut = body.index("\n") + 1 if "\n" in body else len(body)
    return body[cut:].lstrip("=").strip()


def flat(text):
    """Текст раздела одной строкой: многострочный WHEN в таблице или списке читается как обрыв."""
    return " ".join((text or "").split())


# Граница «функция / карточка инструмента» и перечень предписанных инструментов больше здесь не
# собираются (узел FUNC-SEARCH): их спрашивают база и регистр `@mcp.tool()` сервера —
# `tools/rules_functions.py`. Прежние помощники `tool_register`, `claimed_tools`, `split_children`
# и `functions_block` сняты вместе с блоком: порождать перечень из того же состава, который он
# перечисляет, — значит держать в карточке слоя текст, отстающий от неё же.


def mcp_section():
    """Раздел `===MCP` карточки слоя целиком: общие записи слоя + указатель на поиск функций.

    Раздел пишется целиком, а не правится по блокам (узел GENERAL-KB): правка по заголовку
    сохраняла в разделе всё, что в нём стояло, и вторая точка правки оставалась вторым источником
    правил. Указатель больше не порождается дочерними карточками (узел FUNC-SEARCH): перечень,
    который генерирует тот же состав, что он перечисляет, остаётся правдой только до ближайшей
    пересборки, а в карточке, которую читают всегда, занял 4 059 симв. и вывел её за
    ALWAYS_BUDGET_CHARS (14 994 при пороге 12 000).
    Порядок тот же: сначала общая часть, указатель замыкает содержательную часть раздела.
    """
    return "\n\n".join([GENERAL_TEXT, POINTER_HEAD])


def rebuild_parent(cur, dry=False, force_summary=False):
    """Пересобрать `===MCP` (общие записи и указатель), `===LINKS` и `===INDEX` карточки слоя.

    Перечни читаются из базы, а не пишутся в скрипте: список, заведённый руками, отстаёт от дерева
    на одну карточку и врёт про покрытие слоя. Прежний слой (`kb-rules:<...>`) перечисляется только
    живыми строками: снять ссылки раньше, чем перенесены правила, значило бы остаться без входа в
    карточки, но и перечислять снятую строку как «правило ещё действует» — значит выдать карантин за
    правило (замер 25.10.2026: живых прежних строк — ноль).

    Общая часть восстанавливается текстом `LAYER_SUMMARY`, если её в строке нет: карточка без
    ответа «что это за сервер» читается как перечень, а не как карточка слоя.
    """
    cur.execute("SELECT answer FROM knowledge_snippets WHERE question = %s AND source_url = %s",
                (LAYER_ADDRESS, RL.source_url(LAYER_ADDRESS)))
    row = cur.fetchone()
    if not row:
        print(f"⚠️ карточки {LAYER_ADDRESS} в базе нет — пересобирать нечего.")
        return None
    answer = row["answer"]
    if not answer.lstrip().startswith("===SUMMARY"):
        answer = LAYER_SUMMARY + "\n\n" + answer.lstrip("\n")
        print(f"⚠️ {LAYER_ADDRESS}: общая часть в строке отсутствовала — восстановлена "
              f"текстом LAYER_SUMMARY")
    elif force_summary:
        answer = replace_section(answer, "SUMMARY", LAYER_SUMMARY.split("\n", 1)[1])
        print(f"⚠️ {LAYER_ADDRESS}: общая часть перечитана текстом LAYER_SUMMARY (--summary)")
    answer = replace_section(answer, "MCP", mcp_section())
    new_table, new_addrs, new_count = tree_children(cur)
    old_table, old_addrs, old_count = layer_links(cur, LAYER)
    head = f"карточки дерева — уровень 3, слой `{NAMES[LAYER]}` ({new_count}):\n{new_table}"
    note = ("\n\nжурнал (`journal`) и проверки (`checks`) этого слоя — отдельные сущности дерева, "
            "в перечень правил не кладутся: снимок прежних правил и способ проверки не являются "
            "действующим правилом. Читает их дамп отдельными вариантами: `-v 5` (журнал), `-v 6` "
            f"(проверки); в полном отчёте `-v 3` они лежат разделами `===CHECKS` и `===JURNAL` "
            f"в конце файла. Правил без перечней и без этих сущностей — вариант 1, он же "
            f"по умолчанию.")
    if old_count:
        links = (f"{head}\n\nпрежний слой `{LAYER}:<...>` — в дерево ещё не переразвёрнут "
                 f"({old_count} карточек, правила ещё действуют):\n{old_table}{note}")
        index = "\n".join(new_addrs + old_addrs)
    else:
        links = (f"{head}\n\nпрежний слой `{LAYER}:<...>` переразвёрнут в дерево целиком: "
                 f"отдельных карточек слоя больше нет{note}")
        index = "\n".join(new_addrs)
    answer = replace_section(answer, "LINKS", links)
    answer = replace_section(answer, "INDEX", index)
    if dry:
        print(f"• {LAYER_ADDRESS} — answer {len(answer)} симв., детей {new_count}, прежних "
              f"{old_count}")
        return len(answer), new_count, old_count, answer
    cur.execute("UPDATE knowledge_snippets SET answer = %s, updated_at = NOW() WHERE question = %s "
                "AND source_url = %s", (answer, LAYER_ADDRESS, RL.source_url(LAYER_ADDRESS)))
    return len(answer), new_count, old_count, answer


# ------------------------------------------------------------------ точка входа
def main():
    parser = argparse.ArgumentParser(
        description="Карточки третьего уровня слоя правил 1c-knowledge-base")
    parser.add_argument("--dry-run", action="store_true", help="показать состав, в БД не пишет")
    parser.add_argument("--links-only", action="store_true",
                        help="пересобрать перечень слоя, тексты правил не трогать")
    parser.add_argument("--summary", action="store_true",
                        help="перечитать общую часть карточки слоя текстом LAYER_SUMMARY")
    args = parser.parse_args()

    with get_cursor() as cur:
        if args.links_only:
            rebuild_parent(cur, force_summary=args.summary)
            return 0
        for leaf, text, aliases_ru in CARDS:
            snippet_id, action = write_rule(cur, leaf, text, aliases_ru, kind=KIND_FUNCTIONAL,
                                            dry=args.dry_run)
            if action != "dry-run":
                print(f"✅ {LAYER_ADDRESS}{leaf} id={snippet_id} {action} answer={len(text)}")
        if not args.dry_run:
            ensure_layer_ancestor_alias(cur)
        rebuilt = rebuild_parent(cur, dry=args.dry_run, force_summary=args.summary)
        if rebuilt and not args.dry_run:
            print(f"✅ {LAYER_ADDRESS} перечислено: детей {rebuilt[1]}, прежних {rebuilt[2]}, "
                  f"answer={rebuilt[0]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())




