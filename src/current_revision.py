"""Единая точка доступа к текущему состоянию содержимого выгрузки (узел V19, S1-S5).

Зачем. С узла V19 строки семи таблиц внешнего объекта версионированы: на один `uuid`
приходится цепочка строк с `revision_no` (M1). M5 требует, чтобы «текущее состояние»
обеспечивали сами инструменты, а не договорённость вызывающего. Замер цены узла
(`tools/_v19_read_sites.py`, 18.10.2026) давал 52 SQL-обращения в семи модулях; править
их по одному — значит оставить 52 шанса пропустить фильтр, а одна пропущенная строка
даёт смешанные ревизии в одном ответе (тот самый дефект, из-за которого отклонён
вариант В-3). Поэтому определение «текущего» живёт в одном месте:

  * в схеме — витрины `v_current_*` (их текст создаёт `src/generate_ddl.py`, шаг 1; для уже
    созданных БД — `migrate_v19_revisions.sql` с тем же текстом, иначе `_cmp_ddl.py`
    зафиксирует расхождение — инвариант 9 норматива);
  * в коде — этот модуль: он отдаёт имена витрин и SQL-фрагменты разрешения детей через
    манифест (S4).

Правило для вызывающего (то же, что у `src/quarantine.py` про фильтр карантина): писать
свой `max(revision_no)` в модуле-вызывателе нельзя. Сторожит `tools/_v19_read_sites.py`:
он находит и то, и другое — и прямые чтения базовых таблиц, и собственный `max(revision_no)`.
Пробел S2 закрыт 18.10.2026: модулей, читающих версионируемые таблицы в обход этого файла,
не осталось; `max(...revision_no)` встречается только здесь и в определениях
`v_current_*` из DDL-источника.

Узел V46 (шаг П1) расширяет реестр ещё четырьмя версионными таблицами — свойствами
подсистем и общих модулей конфигурации (`subsystems`, `subsystem_content`, `common_modules`,
`common_module_sources`, миграция `migrate_v46_subsystems_common_modules.sql`): их цепочка
состояния ведётся по `(configuration_uuid, full_name)`, а не по `uuid` ребёнка. Флаг
`is_committed` (решение D11, значение — поправка D12 от 28.10.2026) заведён в каждой
версионной таблице — и в семи таблицах V19, и в четырёх новых, — и входит в `REVISION_COLUMNS`:
значение выводит сама точка доступа из события строки (`commit_flag_for`), а не каждый писатель.
На круг строк текущего состояния он не влияет: правило
«максимальная `revision_no` по ключу цепочки» остаётся единственным (решение A1), поэтому
определения `v_current_*` изменились только списком столбцов. Манифест внешнего объекта
этих таблиц не касается: роднит их с родителем `configuration_uuid`, а не
`children_manifest`, поэтому манифестные словари модуля перечисляют только семь таблиц V19
(`OBJECT_VERSIONED_TABLES`), а таблицы конфигурации — отдельный кортеж
(`CONFIGURATION_VERSIONED_TABLES`); объединяет их `VERSIONED_TABLES`, из которого
выводятся имена витрин и право вызывающего назвать базовую таблицу.

Узел V48 (шаг П1) добавляет в этот кортеж пятую таблицу — свойства параметров сеанса
(`session_parameters`, миграция `migrate_v48_session_parameters.sql`). Её цепочка состояния
ведётся по `(configuration_uuid, object_name)`, а не по `full_name`: у вида нет иерархии
раскладки, и строка заголовка перечисляет детей массивами имён (замеры 2.2 и
`_v48_q2_key_probe.py` плана `docs/CONFIGURATION_SESSION_PARAMETERS_PLAN.md`). Механизм
отбора текущего состояния при этом не меняется: правило «максимальный `revision_no` по ключу
цепочки» остаётся единственным (решение A1), поэтому регистрация узла — одна запись в
кортеже, а не правка определений витрин или этого модуля.

Узел V49 (шаг П1) добавляет в этот кортеж три таблицы содержимого ролей (`roles`,
`role_restriction_templates`, `role_sources`, миграция `migrate_v49_roles.sql`): цепочка
состояния роли и её дескриптора ведётся по `(configuration_uuid, object_name)`, цепочка
текста ограничения — по `(configuration_uuid, name, digest)`, потому что текст различается
парой (имя, отпечаток): один и тот же текст объявляют до 664 ролей, а одно и то же имя в
разных ролях несёт разный текст (замеры 2.8–2.9 плана
`docs/CONFIGURATION_ROLES_PLAN.md`). Механизм отбора текущего состояния при этом не
меняется: правило «максимальный `revision_no` по ключу цепочки» остаётся единственным
(решение A1), поэтому регистрация узла — одна запись в кортеже.

Четвёртая таблица узла — `role_rights` — в кортеже не значится осознанно: своей цепи
ревизий у неё нет, а её ключ `(role_id, target_full_name, right_name)` начинается со
ссылки на конкретную ревизию строки роли. Текущность права выводится из `v_current_roles`,
поэтому витрина `v_current_role_rights` строится связкой, а не поиском максимума. Для
вызывающего это означает разницу в правах: права читаются только через витрину, а
`current_view("role_rights")` и `table_name("role_rights")` отвечают отказом — попросить у
модуля цепь, которой нет, значит получить ложное «текущее состояние».

Два разных вопроса, которые нельзя смешивать (инвариант 2 норматива):

  1. «какая строка цепочки является текущей для своего uuid» — отвечает `v_current_*`
     (максимальный `revision_no` в пределах `uuid`);
  2. «какие дети относятся к текущему состоянию объекта» — отвечает ТОЛЬКО манифест
     текущей ревизии родителя, `external_report.children_manifest` (M3, M4, A1). Строка
     ребёнка, у которой своя цепочка в порядке, но её нет в манифесте, — историческая
     строка, а не сирота; отдельного признака состояния на строке ребёнка нет и не будет
     (решение A1).

Манифест — jsonb на строке заголовка: uuid реквизитов объекта, табличных частей, форм,
макетов и пути модулей `Ext/` (у модулей uuid в выгрузке нет, граница — `file_path`).
Уже существующие манифесты (M3) — `tabular_sections.column_uuids` (колонки ТЧ) и jsonb
`form_ext.items/events/commands` (состав формы) — дублировать не стали: дети ТЧ
разрешаются через `column_uuids` текущей ревизии ТЧ, состав формы читают по её jsonb.

Канон формата манифеста — SQL-витрина `v_current_object_manifest` (`src/generate_ddl.py`,
зеркало — `migrate_v19_revisions.sql`): она читает ключи `attribute_uuids`,
`tabular_section_uuids`, `form_uuids`, `template_uuids`, `module_paths` и разворачивает их
в колонки с теми же именами. Python обязан выдавать ровно те же ключи и ровно те же
значения: манифест, собранный этим модулем, и манифест, который витрина посчитала бы по
фактическим строкам детей, обязаны совпадать, — иначе «состав текущего состояния» зависит
от того, каким из двух способов его спросили (раскрытие узла — `tools/check_v19_revisions.py`).

Ключа `form_ext` в манифеста нет осознанно: у описания формы нет своей цепи ревизий —
`uq_form_ext_form_id_revision` привязывает его к ревизии строки формы, поэтому текущность
`form_ext` следует из `form_uuids`, а не из отдельного списка. Витрина этот ключ не читает.

Элемент `module_paths` — пара `parent_type|file_path`: у модуля нет своего uuid в выгрузке,
поэтому границей его идентичности служит путь файла (тот же ключ, что у частичного
`uq_bsl_modules_parent_file_revision`). Формат задаёт `MODULE_KEY_SEPARATOR` и шаблон
`MODULE_KEY_EXPR_TPL` (готовое выражение для алиаса — `MODULE_KEY_EXPR` / `module_key_sql()`):
Python (`_module_path`) и SQL собирают один и тот же ключ из этих констант, потому что
манифест сравнивается со строками детей, и расхождение в одном символе читалось бы как
«модуля нет в составе» при исправном манифесте.
"""

from datetime import datetime

# Версионируемые таблицы содержимого внешнего объекта (узел V19): цепочка состояния
# ведётся по `uuid` ребёнка, а в ТЕКУЩИЙ СОСТАВ его строки допускаются только через
# манифест родителя (M3, A1). Именно поэтому они входят в манифестные словари этого модуля
# (`_MEMBERSHIP`, `MANIFEST_KEYS`, `VIEW_MEMBER_COLUMNS`, `MANIFEST_MEMBERS`).
OBJECT_VERSIONED_TABLES = (
    "external_report", "attributes", "tabular_sections",
    "forms", "form_ext", "templates", "bsl_modules",
)

# Версионируемые таблицы свойств конфигурации (узел V46, шаг П1): цепочка состояния ведётся
# по (configuration_uuid, full_name) — full_name является естественным ключом объекта
# метаданных (замер 2.3 плана docs/CONFIGURATION_OBJECT_PROPERTIES_PLAN.md). Роднит эти
# строки не манифест внешнего объекта, а заголовок конфигурации по `configuration_uuid`,
# поэтому в манифестных словарях их нет ОСОЗНАННО: у подсистемы и общего модуля нет
# членства в составе внешнего объекта, и «сиротой» по манифесту они быть не могут.
# Разрешение детей конфигурации — отдельная задача (шаг П3), здесь только круг строк
# текущего состояния и право имени базовой таблицы.
#
# Узел V48 (шаг П1) добавляет пятую таблицу — свойства параметров сеанса
# (`session_parameters`, миграция `migrate_v48_session_parameters.sql`). Ключ цепочки у неё
# другой — (configuration_uuid, object_name): у вида нет иерархии раскладки, поэтому
# full_name совпадает с object_name (замер 2.2 плана
# docs/CONFIGURATION_SESSION_PARAMETERS_PLAN.md), а строка заголовка перечисляет детей
# массивами имён и uuid в ней не хранится (замер _v48_q2_key_probe.py). Различие ключей
# двух таблиц одной группы — не случайность и не повод для общего контейнера: форму ключа
# задаёт то, чем объект различается в выгрузке (правило
# rules:core-rules:functional:per-block-table-view-checks). Манифестных словарей это не
# касается по той же причине, что и строки V46.
#
# Узел V49 (шаг П1) добавляет ещё три таблицы — содержимое ролей (`roles`,
# `role_restriction_templates`, `role_sources`, миграция `migrate_v49_roles.sql`). Ключ
# цепочки у них начинается с configuration_uuid и продолжается натуральным ключом строки:
# (configuration_uuid, object_name) у роли и у её дескриптора — роль различается именем в
# границах конфигурации, а её uuid совпадает со строкой индекса состава в 1 202 случаях из
# 1 202; (configuration_uuid, name, digest) у текста ограничения — дедупликация по паре
# (имя, отпечаток) выведена из замера: 1 386 вхождений дают 9 различных текстов, один и тот
# же текст объявляют до 664 ролей, а одно имя в разных ролях несёт разный текст
# (замеры 2.8–2.9 плана docs/CONFIGURATION_ROLES_PLAN.md). Форма ключа снова задаётся тем,
# чем строка различается в выгрузке, а не общностью группы (правило
# rules:core-rules:functional:per-block-table-view-checks).
#
# Четвёртая таблица узла — `role_rights` — в этом кортеже НЕ значится ОСОЗНАННО: своей
# цепи ревизий у неё нет. Её ключ (role_id, target_full_name, right_name) начинается со
# ссылки на конкретную ревизию строки роли (Q2, вариант A; замер: повторов цели внутри
# файла — 0, повторов имени права у цели — 0), поэтому текущность права выводится из
# `v_current_roles`, а не из собственного max(revision_no). Витрина v_current_role_rights
# при этом существует и строится связкой — требование п.2 «у каждого блока своя витрина
# текущего состояния» выполняется и без собственной цепи. Для вызывающего это означает:
# права читаются только через витрину, а current_view("role_rights") и
# table_name("role_rights") отвечают отказом — попросить у модуля цепь, которой нет,
# значит получить ложное «текущее состояние».
#
# Узел V50 (шаг П1) добавляет пятую группу — общие реквизиты (`common_attributes`,
# миграция `migrate_v50_common_attributes.sql`, позиция 2.5 нормативного списка). Ключ
# цепочки — (configuration_uuid, object_name): иерархии раскладки у вида нет, индекс
# состава моделирует только верхний уровень (строк `CommonAttribute.<Имя>.<что-то>` в
# четырёх выгрузках ноль), а строка заголовка перечисляет детей массивом имён и uuid в
# ней не хранится (замеры 2.9 плана docs/CONFIGURATION_COMMON_ATTRIBUTES_PLAN.md).
# Граница configuration_uuid обязательна и здесь: 7 имён вида имеют идентичные uuid в
# BGU2 и BP3 (замер 2.8) — тот же урок V47.
#
# Вторая таблица узла — `common_attribute_targets` — в кортеже НЕ значится ОСОЗНАННО по
# той же причине, что role_rights: своей цепи ревизий у неё нет, её ключ
# (common_attribute_id, ordinal) начинается со ссылки на конкретную ревизию строки
# реквизита (замер 2.4: повторов цели внутри одного реквизита — 0, поэтому ordinal
# различает записи и одновременно сохраняет порядок перечня). Витрина
# v_current_common_attribute_targets существует и строится связкой с
# v_current_common_attributes. Отличие от V49 здесь одно и оно названо: uuid общих
# реквизитов общие для разных конфигураций, поэтому uuid в ключ не кладётся вовсе —
# граница конфигурации держится ссылкой на строку родителя.
#
# Следствие, которое обязано быть названо до шага П4: регистрация таблицы в этом кортеже
# расширяет круг стадии S4 (`CHILD_TABLES` = кортеж минус чужие стадии), а своей константы
# круга у вида ещё нет — она появляется шагом П4 вместе со стадией `s4e_common_attributes`
# (тот же порядок, что ROLE_TABLES узла V49, и та же ловушка: проба `_v46_p4_writer_probe.py`
# падает на KeyError, пока стадия не объявила свои таблицы). Писатель таблицы появляется
# шагом П3, до него версионируемая таблица без писателя — это окно, а не состояние нормы.
# Узел V51 (шаг П1) добавляет шестую группу — план обмена (`exchange_plans`,
# `exchange_plan_content`, `commands`, миграция `migrate_v51_exchange_plans.sql`, позиция 2.6
# нормативного списка «Структура конфигурации.txt»). Ключ цепочки строки вида —
# (configuration_uuid, object_name), как у параметров сеанса V48: имя вида уникально в
# конфигурации, а uuid вида повторяется между конфигурациями, выросшими из общей базы
# (замер 3.2 плана docs/CONFIGURATION_EXCHANGE_PLANS_PLAN.md).
#
# Ключ детей — (configuration_uuid, parent_uuid, uuid), у форм и макетов —
# (configuration_uuid, parent_uuid, name): таблицы детей общие со слоем внешнего объекта
# (Q1, вариант A), а ногу области видимости в них внёс этот же шаг. Для строк внешнего
# объекта нога равна parent_uuid (правило (б) оператора), и её выводит писатель
# (`external_table_writer`, вид значения `copy:parent_uuid`), а не разбор выгрузки.
#
# Перечень `<Content>` (`exchange_plan_content`) версионируется ОБЩЕЙ с родителем цепью
# (Q6, вариант A): своей истории у него нет, витрина разрешает его связкой по
# (object_uuid, revision_no) строки вида — тот же порядок, что `subsystem_content` V46.
# Новая таблица `commands` DEFAULT вида родителя не получает: у внешнего объекта команд
# метаданных нет, поэтому писатель обязан назвать `parent_type` явно.
#
# Круг стадии S4 от регистрации не расширяется: таблицы вида вычтены своей константой
# `EXCHANGE_PLAN_TABLES` (src/configuration_load_contract.py). Причина названа узлами V49/V50:
# проба `_v46_p4_writer_probe.py` падала на KeyError, пока стадия не объявляла свой круг.
#
# Узел V52 (01.11.2026, позиция 2.7 нормативного списка — критерии отбора,
# `filter_criteria`, миграция `migrate_v52_filter_criteria.sql`) добавляет в круг ОДНУ
# таблицу. Ключ цепочки — (configuration_uuid, object_name), как у V48/V50/V51: имя вида
# уникально в конфигурации, а uuid вида повторяется между конфигурациями — замер раздела 1.3
# плана docs/CONFIGURATION_FILTER_CRITERIA_PLAN.md даёт 14 различных uuid на 15 верхних
# строк вида и семь совпадающих имён (в отличие от V48/V50/V51, где коллизия uuid была
# множественной, здесь — одна пара; вывод тот же).
# `filter_criterion_content` в круг НЕ вносится осознанно и это названо, а не обойено:
# своей цепи ревизий у строк условия нет (Q2, вариант A по прецеденту
# `common_attribute_targets` V50) — их ключ начинается с `filter_criterion_id`, то есть со
# ссылки на конкретную ревизию строки вида; запись в этом словаре означала бы цепь, которой
# у таблицы нет. Безцепочечная таблица названа исключением
# `CONFIGURATION_UNVERSIONED_TABLES` (src/external_table_writer.py), а её витрина
# `v_current_filter_criterion_content` строится связкой по этому id. Таблицы детей вида
# (формы, команды) в круг не добавляются повторно: они уже в круге V51 (`forms`,
# `form_ext`, `commands`), и V52 пишет в них теми же писателями, не меняя ключей (Q3).
# Узел V53 (02.11.2026, позиция 2.8 нормативного списка — подписки на события,
# `event_subscriptions`, миграция `migrate_v53_event_subscriptions.sql`) добавляет в круг
# ОДНУ таблицу. Ключ цепочки — (configuration_uuid, object_name), как у V48/V50/V51/V52:
# имя вида уникально в конфигурации, а uuid вида повторяется между конфигурациями — замер
# `_v53_m1_probe.py` (раздел 1.3 плана docs/CONFIGURATION_EVENT_SUBSCRIPTIONS_PLAN.md)
# даёт 162 общих uuid и 192 общих имён у BGU2 и BP3; 772 верхние строки вида дают 610
