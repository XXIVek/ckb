#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Карантин ошибочных сниппетов (узел Q1, вариант A: зарезервированный тег).

Зачем. Сниппет бывает ошибочным: авто-сниппет построен по объявлению, которое не является
назначением объекта, ручной сниппет написан неверно. Удалять такую строку сразу — значит
потерять и её саму, и причину. Проект уже различает «снять» и «удалить»: у алиасов мягкое
снятие (`config_aliases.active = false`). У сниппетов колонки `active` или
`marked_for_deletion` в схеме нет, а вариант B (новая колонка в обеих базах) оператором не
выбран, поэтому карантин — зарезервированный тег в уже существующей колонке `tags`:

  * `local_doc.knowledge_snippets.tags` — `text[]`, GIN `idx_snippets_tags`;
  * `ckb_1c_configurations.config_snippets.tags` — `text[] NOT NULL DEFAULT '{}'`.

Схема не меняется ни на колонку, поэтому `_cmp_ddl.py` остаётся зелёным, а витрины (они
считают строки, а не смысл тегов) не переписываются. Цена решения называется прямо:
витрина `v_config_enrichment` про карантин не знает, число помеченных считается отдельным
запросом инструментов; на стороне `config_snippets` GIN по тегам нет — фильтр идёт после
индекса по `parent_uuid`, что для строк одного объекта достаточно.

Соглашение (одинаковое для обоих контуров):

  * `MARKER` — единственная метка карантина. Её ставят только инструменты пометки;
    генератор обогащения, загрузчик выгрузки и автоалиасы её не создают;
  * причина — второй тег `mark-for-deletion:reason=<текст>`. Отдельной колонки под причину
    нет (следствие варианта A), а остаться без причины — значит не ответить оператору,
    почему строку нельзя показывать;
  * любой читающий инструмент скрывает помеченные строки по умолчанию и отдаёт их только
    по `include_marked=True`, обязательно с явным флагом в выводе;
  * метка переживает перегенерацию обогащения: генератор переносит её по идентичности
    строки `(parent_uuid, source_kind, source_uuid, question)` — тот же ключ, что у
    уникального индекса `uq_config_snippets_object_source`. Иначе карантин авто-сниппета
    исчезал бы при каждом `generate_config_enrichment_tool`;
  * физически снимает строку только `tools/purge_marked_snippets.py`.
"""

MARKER = "mark-for-deletion"
# Тег причины строится из метки: `mark-for-deletion` + `:reason=` + текст. Выводить префикс
# отдельным литералом нельзя: SQL-разбор причины (reason_expr_*) собирает тот же префикс из
# значения параметра MARKER, и рассогласование в один символ (двоеточие) делает его слепым —
# разделитель не находится, и база отвечает пусто вместо причины (замер 16.10.2026).
REASON_SUFFIX = ":reason="
REASON_PREFIX = MARKER + REASON_SUFFIX
MAX_REASON_CHARS = 200          # причина — пояснение, а не второй текст сниппета

# Параметры для SQL-фрагментов ниже: массив из одной метки сравнивается с тегами строки
# оператором пересечения (&&) — так же, как фильтр категории в search_docs.
MARK_ARRAY = [MARKER]

# Имена именованных параметров psycopg2. Их два, потому что у одного имени не может быть
# двух типов: фильтр карантина сравнивает массив тегов (нужен массив из метки), а разбор
# причины режет строку по префиксу `mark-for-deletion:reason=` (нужна сама метка).
# Держать эти имена в каждом модуле по отдельности — значит получить рассинхрон.
MARK_PARAM = "mark"        # MARK_ARRAY для условий && 
MARK_TAG_PARAM = "marktag"  # MARKER для разбора причины


def is_marked(tags):
    """Помечена ли строка к удалению (по списку тегов, полученному из БД)."""
    return MARKER in {str(tag).strip() for tag in (tags or [])}


def reason_of(tags):
    """Причина пометки (из тега `mark-for-deletion:reason=…`) или пустая строка."""
    for tag in (tags or []):
        text = str(tag).strip()
        if text.startswith(REASON_PREFIX):
            return text[len(REASON_PREFIX):]
    return ""


def with_mark(tags, reason=None):
    """Новый список тегов: исходные теги + метка (+ тег причины, если она задана).

    Порядок исходных тегов сохраняется, дубликаты снимаются: метка идемпотентна,
    повторная пометка не плодит вторую строку и не портит теги сниппета.
    """
    kept = [str(tag).strip() for tag in (tags or []) if str(tag).strip()]
    kept = [tag for tag in kept if tag != MARKER and not tag.startswith(REASON_PREFIX)]
    if reason is not None and str(reason).strip():
        text = " ".join(str(reason).split())[:MAX_REASON_CHARS]
        kept.append(REASON_PREFIX + text)
    kept.append(MARKER)
    seen, unique = set(), []
    for tag in kept:
        if tag in seen:
            continue
        seen.add(tag)
        unique.append(tag)
    return unique


def without_mark(tags):
    """Снять карантин: убрать метку и тег причины, остальные теги не трогать."""
    return [str(tag).strip() for tag in (tags or [])
            if str(tag).strip() and str(tag).strip() != MARKER
            and not str(tag).strip().startswith(REASON_PREFIX)]


def strip_reserved(tags):
    """Выбросить зарезервированные теги из тегов, которые принёс оператор.

    Карантин — состояние, которое ставят инструменты пометки, а не ручные аргументы:
    иначе тег появился бы в строке без причины и без карточки пометки. Возвращает
    (чистые теги, был_ли_убран_зарезервированный).
    """
    cleaned, removed = [], False
    for tag in (tags or []):
        text = str(tag).strip()
        if not text:
            continue
        if text == MARKER or text.startswith(REASON_PREFIX):
            removed = True
            continue
        cleaned.append(text)
    return cleaned, removed


def sql_not_marked(column="tags"):
    """Условие «строка НЕ в карантине» (параметр — MARK_ARRAY).

    COALESCE нужен для local_doc: там `tags` nullable. В `config_snippets` колонка
    NOT NULL DEFAULT '{}', но фрагмент один на оба контура, чтобы формулировка не
    расходилась.
    """
    return f" AND NOT (COALESCE({column}, ARRAY[]::text[]) && %s::text[])"


def sql_marked(column="tags"):
    """Условие «строка в карантине» (параметр — MARK_ARRAY)."""
    return f" AND (COALESCE({column}, ARRAY[]::text[]) && %s::text[])"


def sql_not_marked_named(column="tags", param="mark"):
    """То же, что sql_not_marked, но для именованных параметров psycopg2 (%(mark)s).

    Оба стиля параметров в проекте уже используются (поиски enrichment идут на dict),
    поэтому фрагменты обязаны существовать для обоих, иначе в одном месте фильтр был бы
    позиционным, в другом — именованным, и их легко было бы потерять по отдельности.
    """
    return (f" AND NOT (COALESCE({column}, ARRAY[]::text[]) "
            f"&& %({param})s::text[])")


def sql_marked_named(column="tags", param="mark"):
    """Условие «строка в карантине» для именованных параметров."""
    return f" AND (COALESCE({column}, ARRAY[]::text[]) && %({param})s::text[])"


def marked_flag(tags):
    """Флаг для вывода инструментов: строка обязана быть помечена явно."""
    return " ⚠️помечен к удалению" if is_marked(tags) else ""


# ---------------------------------------------------------------------------
# Готовые фрагменты для подстановки в уже собранный WHERE (без ведущего AND).
#
# Функции sql_not_marked()/sql_marked() пригодны там, где условие дописывается к
# существующему списку через " AND ". Списки вида `where = [ ... ]` и запросы, где
# условие идёт первым, требуют фрагмент без ведущего союза. Держать два написания
# одного условия в разных модулях — значит получить два разных фильтра карантина,
# поэтому оба вывода строятся от одного источника (функций выше).
# ---------------------------------------------------------------------------

def _bare(fragment):
    """Тот же фрагмент условия, но без ведущего "AND" — для позиции первого условия."""
    text = fragment.strip()
    if text.upper().startswith("AND "):
        text = text[4:].strip()
    return text


NOT_MARKED_SQL = _bare(sql_not_marked())
MARKED_SQL = _bare(sql_marked())
NOT_MARKED_SQL_NAMED = _bare(sql_not_marked_named())
MARKED_SQL_NAMED = _bare(sql_marked_named())

# Признак карантина в выдаче читающих инструментов (строка обязана быть явной).
# Стиль параметра в выражении обязан совпадать со стилем всего запроса: смешать
# %s и %(mark)s в одном SQL нельзя.
MARKED_FLAG_SQL = f"({MARKED_SQL_NAMED}) AS marked"
MARKED_FLAG_POSITIONAL_SQL = f"({MARKED_SQL}) AS marked"

# Причина пометки из тегов, читаемая самой базой (чтобы перечень карантина не
# зависел от Python-разбора тегов). Именованный вариант — для запросов на dict,
# позиционный — для запросов на tuple; параметр везде MARKER.
#
# Имя именованного параметра различается, потому что в одном запросе уже занят `mark`
# под массив тегов (условие карантина), а здесь нужен сам текстовый маркер: один и тот же
# параметр не может быть и массивом, и строкой. Значит вызывающий код передаёт имя.
def _reason_expr(placeholder):
    """Общий разбор причины для обоих стилей параметров.

    Один текст выражения на оба стиля: различается только вид placeholder (`%(mark_tag)s`
    против `%s`), потому что два написания одного разбора — это два разных ответа на вопрос
    «почему помечено». Параметр подставляется ровно один раз (через derived table `bond`):
    позиционный стиль при повторе `%s` потребовал бы передавать MARKER несколько раз, и это
    ловушка, а не смысл.
    """
    prefix = f"{placeholder} || '{REASON_SUFFIX}'"
    return ("coalesce((SELECT nullif(substr(t.tag, char_length(bond.pfx) + 1), '') "
            "FROM (SELECT " + prefix + " AS pfx) AS bond, "
            "unnest(COALESCE(tags, ARRAY[]::text[])) AS t(tag) "
            "WHERE left(t.tag, char_length(bond.pfx)) = bond.pfx LIMIT 1), '')")


def reason_expr_named(param=MARK_TAG_PARAM):
    """Выражение SQL: причина пометки из тегов (именованный параметр = MARKER).

    Узел Q3 (три дефекта одного выражения, все подтверждены живыми запросами):

    1. У `split_part` ровно три аргумента — строка, разделитель и номер части. Запись
       с двумя аргументами отбрасывается самой базой:
       `function split_part(text, text) does not exist` — запрос не выполняется вовсе.
    2. Разделитель обязан равняться REASON_PREFIX, то есть метке плюс `:reason=`.
       Разделитель без префикса (`reason=`) в тегах не встречается: запрос выполнялся,
       но на вопрос «почему помечено» отвечал пусто.
    3. Разбор не должен зависеть от того, какой тег стоит после причины. `with_mark` кладёт
       MARKER ПОСЛЕ тега причины, поэтому склеенная строка выглядит так
       `mark-for-deletion:reason=a=1,mark-for-deletion`, а `split_part(..., 2)` берёт текст до
       СЛЕДУЮЩЕГО вхождения разделителя — при единственном вхождении это конец строки. Замер
       16.10.2026 (семь раскладок тегов): `split_part` отвечает `'a=1,mark-for-deletion'`, там
       где `reason_of` отдаёт `'a=1'`; при теге причины в середине хвост другой строки
       (`'a=1,zz'`). То есть метка искажала собственную причину, и это не видно по ошибке —
       запрос выполнялся. Поэтому причина ищется по каждому тегу отдельно (unnest + left/
       substr): тег с префиксом находится на любой позиции, а причиной считается только текст
       после префикса — ровно как в Python-разборе `reason_of`.

    Значение параметра — везде MARKER; имя именованного параметра различается, поэтому
    вызывающий обязан передать `{param: MARKER}` наравне с массивом тегов `{mark: [MARKER]}`.
    """
    return _reason_expr(f"%({param})s")


def reason_expr_positional():
    """Выражение SQL: причина пометки из тегов (позиционный параметр = MARKER).

    Тот же разбор, что и в именованном варианте, — только стиль параметра другой
    (запросы на tuple против dict). Смешивать %s и %(mark)s в одном SQL нельзя.
    Порядок позиционных значений задаёт текст SQL: %s этого выражения стоит там, где
    подставлено само выражение, а не в конце запроса — вызывающий считает позиции по
    итоговой строке, а не по своему списку аргументов.
    """
    return _reason_expr("%s")


REASON_EXPR_NAMED = reason_expr_named()
REASON_EXPR_POSITIONAL = reason_expr_positional()

# Условие «строка помечена» для подстановки в SELECT-список или WHERE без ведущего AND:
# то же определение, что и у фильтров перечней (иначе счётчик и перечень разойдутся).
MARKED_COND_NAMED = f"COALESCE(tags, ARRAY[]::text[]) && %({MARK_PARAM})s::text[]"
MARKED_COND_POSITIONAL = "COALESCE(tags, ARRAY[]::text[]) && %s::text[]"

