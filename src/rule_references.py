"""Корзины ссылок правила на файлы: происхождение, история, битая ссылка (узел COV-BASKETS).

Зачем один модуль. Один и тот же вопрос — «названного карточкой файла нет в проекте: это
провал или правда о прошлом?» — решают два инструмента:
`tools/check_rule_tool_coverage.py` (часть B, разделы `CHECK`/`TOOLS` действующих карточек)
и `tools/_named_artifacts_audit.py` (проза карточек, куда разделный сторож не заходит).
Своя копия классификации у каждого означает, что каждый проверяет свою копию, а не тот
порядок, по которому живое правило говорит о снятом (тот же мотив, что MUST 4 в
`rules:checks:layer-verification`: свой предикат сверял бы себя, а не поиск). Здесь держатся
метки и сам предикат.

Граница (названа, а не обойена): чем считается ссылка — разделы или проза, с каким контекстом
строки и как именно ищется файл на диске — остаётся у инструментов. Области у них разные
(раздел контракта обещает проверку здесь и сейчас, проза снимает состояние на дату), и
объединение этих частей стёрло бы границу, названную в самой карточке. Различаются только
корзины — их два инструмента обязаны различать одинаково.

Три корзины:

  provenance — ссылка на прежний файл правил (`.clinerules/<слой>_Rule.md`), содержимое
               которого перенесено в базу правилами, и карточки журнала: они называют источник
               снимка, и отсутствующий источник для них — правда о прошлом, а не битая ссылка;
  history    — строка с маркерами снятого («→», «прежн», «удал», «снят», …) или карточка
               снятого функционала (`:removed`): называть то, чего нет, им предписано;
  broken     — строка утверждает настоящее время («проверка — …», «DDL — …»): файл обязан
               существовать, и это провал проверки.

Без разделения корзин правило о прошлом читается как битая ссылка: прогон 06.11.2026 дал
две «битые» ссылки в живом правиле `rules:checks:layer-verification` — `_layers_tree_probe.py`
(имя, переименованное в `_layer_tree_check.py`, названо в строке с «→») и `_Rule.md` (прежние
файлы правил, названы в строке с «прежние»). Обе — ссылки истории/происхождения, и карточка
тем же текстом предписывает отделять их от битых.
"""

# Снимок прежних текстов и снятый функционал: называть отсутствующее им предписано.
JOURNAL_MARK = ":journal:"
REMOVED_MARK = ":removed"
# Файлы прежних правил, перенесённые в базу правилами: ссылка на них = происхождение текста.
PROVENANCE_DIR = ".clinerules/"

# Маркеры строки-истории — тот же приём, что у check_search_rules_sync (снимок не правится),
# плюс конструкции «названо именно для того, чтобы сказать, что этого нет».
HISTORY_MARKS = (
    "→", "прежн", "удал", "снят", "сним", "перенес", "архив", "ранее",
    "больше нет", "источник", "Источник", "до правки", "замер ",
    "ошибк", "несуществующ", "никогда не было", "файла с таким именем",
)

KIND_PROVENANCE = "provenance"
KIND_HISTORY = "history"
KIND_BROKEN = "broken"

# Контекстом берётся окно строк вокруг совпадения, а не одна строка: тексты карточек
# перенесены посреди предложения, и маркер истории («→», «прежние») стоит на строке соседней с
# названием файла. Одна строка контекста кладёт такую ссылку в битые — прогон 06.11.2026
# показал это на самой карточке `rules:checks:layer-verification`, где рассказ о снятом
# перенесён между строками.
CONTEXT_LINES = 1


def context_window(lines, index: int, ctx_lines: int = CONTEXT_LINES) -> str:
    """Фрагмент текста вокруг совпадения — то, по чему ссылка кладётся в корзину."""
    lo = max(0, index - ctx_lines)
    return "\n".join(lines[lo:index + ctx_lines + 1])


def classify(address: str, context: str, path: str) -> str:
    """Корзина ссылки: происхождение и история правомочны, битая ссылка — провал.

    `address` — адрес карточки, `context` — тот фрагмент её текста, внутри которого стоит
    совпадение (строки берут окном `context_window`: перенос посреди предложения иначе
    размывает маркер истории), `path` — названный путь или имя файла.
    """
    if JOURNAL_MARK in address or path.startswith(PROVENANCE_DIR):
        return KIND_PROVENANCE
    if REMOVED_MARK in address:
        return KIND_HISTORY
    for mark in HISTORY_MARKS:
        if mark in context:
            return KIND_HISTORY
    return KIND_BROKEN
