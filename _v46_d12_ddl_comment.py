#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Одноразовый фиксер: шесть одинаковых комментариев узла V46 в DDL-источнике.

Блок в `src/generate_ddl.py` повторяется шесть раз идентично (таблица объекта и пятеро
детей), поэтому правка делается сверкой по числу вхождений: шесть — правим, иное —
останавливаемся, потому что шестой блок мог измениться отдельно и молчаливая замена
чужого текста исказила бы уже не комментарий узла V46.

Причина правки — поправка D12 к решению D11 (28.10.2026): значение признака коммита
выводит точка доступа `src/current_revision.py`, загрузка заявляет TRUE.
"""
import pathlib

PATH = pathlib.Path("src/generate_ddl.py")
OLD = """    -- узел V46 (D11): строка версии, не помеченная коммитом. Признак заявляет
    -- загрузчик значением FALSE; TRUE ставит событие коммита. Это не признак
    -- «текущей строки» — их круг разрешает манифест родителя (решение A1).
"""
NEW = """    -- узел V46 (D11, словарь значений — поправка D12 от 28.10.2026): признак коммита
    -- строки версии. TRUE заявляет загрузка: строка соответствует источнику, локальных
    -- правок поверх неё нет; FALSE появляется только у ревизии, созданной правкой в базе.
    -- Значение выводит src/current_revision.py (commit_flag_for), а не писатель; DEFAULT
    -- FALSE остаётся маркером «значение не заявлено точкой доступа». Это не признак
    -- «текущей строки» — их круг разрешает манифест родителя (решение A1).
"""
EXPECTED_BLOCKS = 6


def main():
    text = PATH.read_text(encoding="utf-8")
    found = text.count(OLD)
    if found != EXPECTED_BLOCKS:
        print("ОСТАНОВКА: ожидалось %d блока, найдено %d — правка не выполнена"
              % (EXPECTED_BLOCKS, found))
        return 1
    PATH.write_text(text.replace(OLD, NEW), encoding="utf-8")
    print("заменено блоков:", found)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
