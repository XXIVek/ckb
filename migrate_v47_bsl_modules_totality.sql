-- migrate_v47_bsl_modules_totality.sql
-- ============================================================================
-- Узел V47, шаг П1: `bsl_modules` становится таблицей с тотальным ключом
--       (решения оператора Q1/Q2 от 28.10.2026, план
--       docs/CONFIGURATION_OBJECT_MODULES_PLAN.md, разделы 5.1 и 5.2).
-- Дата: 2026-10-28.
--
-- Почему. Узел V47 пишет в `bsl_modules` модули объектов конфигурации
-- (`parent_type = 'configuration_objects'`, `parent_uuid` = uuid объекта-владельца).
-- Ключ текущего состояния у этой таблицы уже есть — частичный уникальный индекс
-- `uq_bsl_modules_parent_file_revision (parent_uuid, file_path, revision_no)
--  WHERE parent_uuid IS NOT NULL` (узел V19), а витрина `v_current_bsl_modules`
-- разрешает состояние той же парой. Ничего нового индексом задавать не нужно; нужно
-- снять зависимость правила от NULL:
--
--   * при `parent_uuid IS NULL` или `file_path IS NULL` предикат индекса и правило
--     витрины перестают работать — строки разных ревизий одного модуля не различаются;
--   * при `configuration_uuid IS NULL` вопрос «модули какой конфигурации» для строки
--     внешнего объекта остаётся без ответа, а снятие строк круга узла идёт по паре
--     (`configuration_uuid`, `parent_type`) — прецедент V46 (`remove_common_module_texts`).
--
-- Решение оператора (28.10.2026), пункт 1 раздела 5.1 плана: любая строка `bsl_modules`
-- обязана иметь заполненными `configuration_uuid` и `parent_uuid`; если запись есть, она
-- обязана иметь путь (раздел 5.2). Значит обе uuid-колонки и `file_path` переходят на
-- NOT NULL, а писатель отклоняет строку до записи, а не пишет половину ключа.
--
-- Заполнение живых строк. Замер 28.10.2026: в таблице ДВЕ строки (id 306, 307), обе
-- `parent_type = 'external_report'`, `parent_uuid` заполнен, `configuration_uuid` пуст,
-- `file_path` заполнен; строк с `parent_uuid IS NULL` — 0. Для внешнего объекта оба uuid
-- совпадают и равны uuid самого объекта — такова физическая запись модели оператора
-- (внешний объект сам является корнем своего содержимого, отдельной строки конфигурации у
-- него нет). Именно это и пишет шаг 1, а не «неизвестную конфигурацию».
--
-- Что снимается. Частичный уникальный индекс V46
-- `uq_bsl_modules_config_module_revision (configuration_uuid, module_type, module_name,
--  revision_no) WHERE parent_uuid IS NULL` закрывал слепую зону строк конфигурации, у
-- которых `parent_uuid` пуст. После NOT NULL на `parent_uuid` таких строк не может быть
-- вовсе, то есть индекс не совпадёт ни с одной строкой. Он снимается: мёртвый индекс в
-- схеме — это обещание правила, которое уже не действует. Следствие называется прямо:
-- проба `_v46_p2_probe.sql` (группа P3 — «дубликат строки модуля конфигурации
-- отклоняется») с этой миграции работает иначе: строка без `parent_uuid` отклоняется как
-- нарушение NOT NULL, а не как нарушение уникальности.
--
-- Чего миграция НЕ делает (названо, а не опущено):
--   * не вводит `code_state`, `code_chars`, `code_bytes` — решение Q2: отсутствие строки
--     означает пустой модуль, состояний у модулей объектов в таблице нет;
--   * не вводит CHECK на `code IS NOT NULL` — он сломал бы контракт V46, где пустой общий
--     модуль остаётся строкой с `code IS NULL` и `code_size = 0` (`common_module_text_row`).
--     Граница «строка есть ⇒ код есть» держится писателем узла V47 и его проверкой, а не
--     схемой;
--   * не меняет витрину `v_current_bsl_modules`: её правило не изменилось, изменилась
--     только тотальность входных данных;
--   * не трогает таблицы модулей предопределённых программ корня (узел V44) и таблицу-
--     дескриптор `common_module_sources` (узел V46).
--
-- Итоговое состояние совпадает с чистой установкой: шаг 2 —
-- create_1c_configurations_db.sql. Сверка — _cmp_ddl.py.
--
-- Миграция идемпотентна: повторный прогон схему не меняет. Ошибка любого шага —
-- ROLLBACK, полусменённой схемы не остаётся. Запускать с -v ON_ERROR_STOP=1.
-- ============================================================================

BEGIN;

-- 1. Заполнение ссылки на заголовок для строк внешнего контура.
--    Условие держится по `parent_type`, а не по «`parent_uuid` не пуст»: внешний объект —
--    единственный контур, у которого конфигурацией считается сам объект (общие модули V46
--    ссылку заполняют сами, модули конфигурации пишутся узлом V47).
UPDATE bsl_modules
   SET configuration_uuid = parent_uuid
 WHERE configuration_uuid IS NULL
   AND parent_uuid IS NOT NULL
   AND parent_type = 'external_report';

-- 2. Тотальность ключа. Порядок: сначала заполнение (шаг 1), затем NOT NULL — иначе
--    ALTER отказывает на существующих строках и миграция не проходит вовсе.
ALTER TABLE bsl_modules
    ALTER COLUMN parent_uuid SET NOT NULL;
ALTER TABLE bsl_modules
    ALTER COLUMN configuration_uuid SET NOT NULL;
ALTER TABLE bsl_modules
    ALTER COLUMN file_path SET NOT NULL;


-- 3. Снятие индекса, который после шага 2 не может совпасть ни с одной строкой
--    (предикат `parent_uuid IS NULL` при NOT NULL-колонке ложен всегда).
DROP INDEX IF EXISTS uq_bsl_modules_config_module_revision;

-- 4. Индекс по ссылке на заголовок остаётся частичным (`WHERE configuration_uuid IS NOT
--    NULL`): после шага 2 предикат не будет истинным ни на одной строке, но определение
--    индекса меняется отдельным узлом — здесь оно не переопределяется, чтобы шаг П1 не
--    смешивал тотальность данных с чисткой схемы. То же относится к
--    `idx_bsl_modules_parent_uuid_revision` и к самому ключу
--    `uq_bsl_modules_parent_file_revision`.
--    Отдельная позиция, которую эта миграция НЕ закрывает:
--    `parent_type TEXT NOT NULL DEFAULT 'external_report'` — значение по умолчанию молча
--    приписывает чужой контур строке, забывшей назвать родителя. Писатель узла V47 обязан
--    называть `parent_type` явно, не полагаясь на DEFAULT; снятие самого DEFAULT — работа
--    отдельного узла, потому что задевает загрузчики внешних объектов.

COMMIT;

-- ---------------------------------------------------------------------------
-- 5. Проверка после применения.
-- ---------------------------------------------------------------------------
-- 5.1. Пустых частей ключа нет ни в таблице, ни в витрине:
-- SELECT count(*) FROM bsl_modules
--  WHERE parent_uuid IS NULL OR configuration_uuid IS NULL OR file_path IS NULL;   -- 0
-- SELECT count(*) FROM v_current_bsl_modules WHERE configuration_uuid IS NULL;     -- 0
--
-- 5.2. Круг строк витрины не изменился (замер до миграции — 2 строки модулей внешних
--      объектов):
-- SELECT count(*) FROM bsl_modules;                                               -- 2
-- SELECT count(*) FROM v_current_bsl_modules;                                     -- 2
-- SELECT count(*) FROM bsl_modules WHERE parent_type = 'external_report'
--   AND configuration_uuid = parent_uuid;                                         -- 2
--
-- 5.3. Мёртвого индекса нет, живой ключ на месте:
-- SELECT indexname FROM pg_indexes WHERE tablename='bsl_modules' ORDER BY 1;
--   -- `uq_bsl_modules_config_module_revision` отсутствует;
--   -- `uq_bsl_modules_parent_file_revision` присутствует.
--
-- 5.4. Повтор той же пары (родитель, путь, ревизия) отклоняется настоящим ключом
--      (вставка с последующим откатом), вторая ревизия — не отклоняется (M1 живёт).
--
